# Builds src/timing.ts from the forced-alignment output (data/aligned.json).
import json, re, sys, os
here = os.path.dirname(os.path.abspath(__file__))
words = json.load(open(os.path.join(here, "../data/aligned.json")))
# display text with punctuation, from the transcript
disp = open(os.path.join(here, "../data/transcript.txt")).read().split()
assert len(disp) == len(words), (len(disp), len(words))
seen = {}
rows = []
for d, w in zip(disp, words):
    base = re.sub(r"[^a-z]", "", w["w"].lower())
    seen[base] = seen.get(base, 0) + 1
    key = base if seen[base] == 1 else f"{base}{seen[base]}"
    rows.append((key, d, w["s"], w["e"]))
out = ["// AUTO-GENERATED by scripts/make_timing.py from CTC forced alignment of the voiceover.",
       "// Times in seconds. Do not edit by hand; re-run the script instead.",
       "export type Word = { key: string; text: string; s: number; e: number };",
       "export const WORDS: Word[] = ["]
for k, d, s, e in rows:
    out.append(f"  {{ key: {json.dumps(k)}, text: {json.dumps(d)}, s: {s:.3f}, e: {e:.3f} }},")
out.append("];")
open(os.path.join(here, "../src/timing.ts"), "w").write("\n".join(out) + "\n")
print("\n".join(f"{k:14s} {s:6.3f}" for k, d, s, e in rows))
